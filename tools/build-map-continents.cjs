/**
 * Builds map-quiz-continents.js: map key (id or cls_*) -> quiz continent
 * - ISO-3166-1 alpha-2: from UN M49 (via all-iso.json region fields)
 * - cls_* keys: from OVERRIDES
 *
 * From project root: node tools/build-map-continents.cjs
 * Requires: tools/all-iso.json
 */
const fs = require("fs");
const path = require("path");

const worldKeysPath = path.join(__dirname, "world-map-key-list.txt");
const isoPath = path.join(__dirname, "all-iso.json");
const outPath = path.join(__dirname, "..", "map-quiz-continents.js");

const worldKeys = fs
  .readFileSync(worldKeysPath, "utf8")
  .split("\n")
  .map((s) => s.trim())
  .filter(Boolean);

const isoRows = JSON.parse(fs.readFileSync(isoPath, "utf8"));

/**
 * @param {{ region: string, "sub-region": string, "intermediate-region": string | null}} row
 * @returns {string}
 */
function continentFromRow(row) {
  const r = row.region;
  if (!r) return "asia";
  if (r === "Europe") return "europe";
  if (r === "Africa") return "africa";
  if (r === "Asia") return "asia";
  if (r === "Oceania") return "oceania";
  if (r === "Americas") {
    const mid = row["intermediate-region"] || "";
    if (mid === "South America") return "southamerica";
    return "northamerica";
  }
  if (r === "Antarctica") return "asia";
  return "asia";
}

/** @type {Record<string, string>} */
const fromIso = {};
for (const row of isoRows) {
  if (row && row["alpha-2"] && row.region) {
    fromIso[row["alpha-2"]] = continentFromRow(row);
  }
}

